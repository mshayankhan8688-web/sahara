async function sleep(ms: number) {
  await new Promise((resolve) => setTimeout(resolve, ms));
}

export async function registerViaApi(request: APIRequestContext, label: string): Promise<TestAccount> {
  const email = `e2e.${label}.${Date.now()}@example.com`;
  const password = "TestHorse99!";
  let lastText = "";
  for (let attempt = 0; attempt < 6; attempt += 1) {
    const response = await request.post(`${API_URL}/api/auth/register`, {
      headers: { "x-heartspace-request": "1", "Content-Type": "application/json" },
      data: { name: `E2E ${label}`, email, password },
    });
    if (response.ok()) {
      const json = (await response.json()) as { token: string; user: { id: string; name: string } };
      return { email, password, token: json.token, user: json.user };
    }
    lastText = await response.text();
    if (response.status() === 429) {
      await sleep(2_000 * (attempt + 1));
      continue;
    }
    throw new Error(`register failed: ${response.status()} ${lastText}`);
  }
  throw new Error(`register failed after retries: ${lastText}`);
}

/** Avoid auth rate limits: inject JWT and open the app. */
export async function openAuthenticatedApp(page: Page, context: BrowserContext, account: TestAccount) {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.addInitScript((token: string) => {
    localStorage.setItem("heartspace.token", token);
  }, account.token);
  await mockAiApis(page);
  await page.goto("/app");
  await expect(page).toHaveURL(/\/app(\/|$)/, { timeout: 20_000 });
}

export async function loginInBrowser(page: Page, email: string, password: string) {
  await page.goto("/login");
  await page.getByLabel(/email or phone/i).fill(email);
  await page.getByLabel(/^password$/i).fill(password);
  await page.getByRole("button", { name: /^login$/i }).click();
  await expect(page).toHaveURL(/\/app(\/|$)/, { timeout: 20_000 });
}

export async function collectConsoleErrors(page: Page) {
  const errors: string[] = [];
  page.on("console", (msg) => {
    if (msg.type() === "error") errors.push(msg.text());
  });
  page.on("pageerror", (err) => errors.push(String(err)));
  return errors;
}

export async function collectFailedRequests(page: Page) {
  const failed: string[] = [];
  page.on("response", (response) => {
    if (response.status() >= 500) failed.push(`${response.status()} ${response.url()}`);
  });
  return failed;
}

export function assertPptxOrDocxZip(buffer: Buffer) {
  expect(buffer.subarray(0, 2).toString("utf8")).toBe("PK");
  expect(buffer.byteLength).toBeGreaterThan(1000);
  expect(buffer.toString("utf8")).toContain("[Content_Types].xml");
}

export function assertPdf(buffer: Buffer) {
  expect(buffer.subarray(0, 4).toString("utf8")).toBe("%PDF");
  expect(buffer.byteLength).toBeGreaterThan(400);
  expect(buffer.toString("latin1")).toContain("%%EOF");
}
